public class Player {
    private String name;
    private int hp;
    private int dmg;
    private String race;
    private String subClass;

    Player(String name, int hp, int dmg, String race, String subClass){
        this.name = name;
        this.hp = hp;
        this.dmg = dmg;
        this.race = race;
        this.subClass = subClass;
    }

    
}
